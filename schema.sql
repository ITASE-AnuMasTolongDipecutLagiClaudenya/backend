create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  age smallint check (age is null or age between 13 and 120),
  gender text,
  pregnancy_status text,
  weight_kg numeric(6,2) check (weight_kg is null or weight_kg between 1 and 500),
  height_cm numeric(6,2) check (height_cm is null or height_cm between 30 and 275),
  activity text,
  goal text,
  is_gym boolean not null default false,
  target_calories numeric(8,2) check (target_calories is null or target_calories between 1 and 10000),
  target_protein_g numeric(8,2) check (target_protein_g is null or target_protein_g between 0 and 1000),
  target_carbs_g numeric(8,2) check (target_carbs_g is null or target_carbs_g between 0 and 2000),
  target_fat_g numeric(8,2) check (target_fat_g is null or target_fat_g between 0 and 1000),
  target_sugar_g numeric(8,2) check (target_sugar_g is null or target_sugar_g between 0 and 1000),
  target_sodium_mg numeric(8,2) check (target_sodium_mg is null or target_sodium_mg between 0 and 10000),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists target_calories numeric(8,2) check (target_calories is null or target_calories between 1 and 10000);
alter table public.profiles add column if not exists target_protein_g numeric(8,2) check (target_protein_g is null or target_protein_g between 0 and 1000);
alter table public.profiles add column if not exists target_carbs_g numeric(8,2) check (target_carbs_g is null or target_carbs_g between 0 and 2000);
alter table public.profiles add column if not exists target_fat_g numeric(8,2) check (target_fat_g is null or target_fat_g between 0 and 1000);
alter table public.profiles add column if not exists target_sugar_g numeric(8,2) check (target_sugar_g is null or target_sugar_g between 0 and 1000);
alter table public.profiles add column if not exists target_sodium_mg numeric(8,2) check (target_sodium_mg is null or target_sodium_mg between 0 and 10000);
alter table public.profiles add column if not exists is_gym boolean not null default false;

create table if not exists public.meals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  serving_size text,
  calories numeric(8,2) not null default 0,
  protein_g numeric(8,2) not null default 0,
  carbs_g numeric(8,2) not null default 0,
  fat_g numeric(8,2) not null default 0,
  sugar_g numeric(8,2),
  sodium_mg numeric(8,2),
  created_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id uuid not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null check (char_length(content) between 1 and 4000),
  created_at timestamptz not null default now()
);

alter table public.chat_messages add column if not exists conversation_id uuid;
update public.chat_messages set conversation_id = gen_random_uuid() where conversation_id is null;
alter table public.chat_messages alter column conversation_id set default gen_random_uuid();
alter table public.chat_messages alter column conversation_id set not null;

create index if not exists meals_user_created_idx on public.meals(user_id, created_at desc);
create index if not exists chat_messages_user_conversation_idx on public.chat_messages(user_id, conversation_id, created_at);

alter table public.profiles enable row level security;
alter table public.meals enable row level security;
alter table public.chat_messages enable row level security;

drop policy if exists "Users read own profile" on public.profiles;
drop policy if exists "Users insert own profile" on public.profiles;
drop policy if exists "Users update own profile" on public.profiles;
drop policy if exists "Users read own meals" on public.meals;
drop policy if exists "Users insert own meals" on public.meals;
drop policy if exists "Users read own chat" on public.chat_messages;
drop policy if exists "Users insert own chat" on public.chat_messages;

create policy "Users read own profile" on public.profiles for select to authenticated using (auth.uid() = user_id);
create policy "Users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = user_id);
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users read own meals" on public.meals for select to authenticated using (auth.uid() = user_id);
create policy "Users insert own meals" on public.meals for insert to authenticated with check (auth.uid() = user_id);
create policy "Users read own chat" on public.chat_messages for select to authenticated using (auth.uid() = user_id);
create policy "Users insert own chat" on public.chat_messages for insert to authenticated with check (auth.uid() = user_id);

grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.meals, public.chat_messages to authenticated;
grant usage, select on sequence public.meals_id_seq, public.chat_messages_id_seq to authenticated;
